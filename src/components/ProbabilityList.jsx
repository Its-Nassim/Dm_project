import { getClassById } from '../config/classes.js'
import './ProbabilityList.css'

export default function ProbabilityList({ probabilities, mock = false, customLabels }) {
  if (!probabilities || !Array.isArray(probabilities) || probabilities.length === 0) {
    return null
  }

  const sorted = [...probabilities].sort((a, b) => a.classId - b.classId)

  return (
    <div className="prob-container" aria-label="Class probabilities">
      <div className="prob-header">
        <h4 className="prob-title">Class probabilities</h4>
        {mock && (
          <span className="prob-mock-badge" title="Generated by client mock">
            Mock response
          </span>
        )}
      </div>

      <div className="prob-list">
        {sorted.map((item) => {
          const meta = getClassById(item.classId, customLabels)
          const pct = Math.max(0, Math.min(100, item.value * 100))
          const formattedPct = `${pct.toFixed(1)}%`

          return (
            <div key={item.classId} className="prob-row">
              <div className="prob-info">
                <span className="prob-label">
                  <span className="prob-id" style={{ color: `var(${meta.token})` }}>
                    Class {item.classId}
                  </span>
                  {' '}· {item.label || meta.name}
                </span>
                <span className="prob-pct num">{formattedPct}</span>
              </div>
              <div
                className="prob-meter-track"
                role="meter"
                aria-label={`Probability for Class ${item.classId} (${meta.name})`}
                aria-valuenow={pct}
                aria-valuemin="0"
                aria-valuemax="100"
              >
                <div
                  className="prob-meter-fill"
                  style={{
                    width: `${pct}%`,
                    backgroundColor: `var(${meta.token})`,
                  }}
                />
              </div>
            </div>
          )
        })}
      </div>
    </div>
  )
}
